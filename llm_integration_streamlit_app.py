import pandas as pd
import streamlit as st

from app.project1.google_llm import MODEL, Recipe, get_dish_recipe

st.set_page_config(page_title="AI Recipe Chef", page_icon="🍲", layout="wide")

DIETARY_OPTIONS = [
    "vegan", "vegetarian", "gluten-free", "dairy-free", "nut-free",
    "halal", "kosher", "low-carb", "keto", "low-sodium",
]


@st.cache_data(show_spinner=False)
def fetch_recipe(dish: str, restrictions: tuple[str, ...], servings: int, model: str) -> dict:
    # Cache by inputs; store as dict so Streamlit can hash/pickle it.
    return get_dish_recipe(dish, list(restrictions), servings, model).model_dump(mode="json")


# ---------- Sidebar ----------
with st.sidebar:
    st.header("Settings")
    model = st.text_input("Gemini model", value=MODEL)
    servings = st.number_input("Servings", min_value=1, max_value=50, value=4)
    restrictions = st.multiselect("Dietary restrictions", DIETARY_OPTIONS)
    custom = st.text_input("Other restrictions (comma-separated)")
    if custom:
        restrictions += [r.strip() for r in custom.split(",") if r.strip()]

# ---------- Main ----------
st.title("🍲 AI Recipe Chef")
st.caption("Powered by Google Gemini with structured (Pydantic) output.")

with st.form("recipe_form"):
    dish = st.text_input("What dish do you want to cook?", placeholder="e.g. Nigerian Jollof Rice")
    submitted = st.form_submit_button("Generate recipe", type="primary")

if submitted:
    if not dish.strip():
        st.warning("Please enter a dish name.")
        st.stop()
    try:
        with st.spinner(f"Cooking up a recipe for {dish}..."):
            st.session_state.recipe = fetch_recipe(
                dish.strip(), tuple(sorted(restrictions)), int(servings), model
            )
    except Exception as e:
        st.error(f"Failed to generate recipe: {e}")
        st.stop()

if "recipe" in st.session_state:
    recipe = Recipe.model_validate(st.session_state.recipe)

    st.header(recipe.dish_name)
    st.write(recipe.description)
    if recipe.dietary_compliance:
        st.markdown(" ".join(f":green-badge[{label}]" for label in recipe.dietary_compliance))

    c1, c2, c3, c4, c5 = st.columns(5)
    c1.metric("Cuisine", recipe.cuisine)
    c2.metric("Servings", recipe.servings)
    c3.metric("Prep", f"{recipe.prep_time_minutes} min")
    c4.metric("Cook", f"{recipe.cook_time_minutes} min")
    c5.metric("Difficulty", recipe.difficulty.value.title())

    tab_ing, tab_steps, tab_subs, tab_nut, tab_json = st.tabs(
        ["🧂 Ingredients", "👩‍🍳 Steps", "🔁 Substitutions", "📊 Nutrition", "🧾 Raw JSON"]
    )

    with tab_ing:
        df = pd.DataFrame([i.model_dump() for i in recipe.ingredients])
        st.dataframe(df, hide_index=True, use_container_width=True)
        st.download_button(
            "Download shopping list (CSV)", df.to_csv(index=False),
            file_name=f"{recipe.dish_name}_ingredients.csv", mime="text/csv",
        )

    with tab_steps:
        for step in sorted(recipe.steps, key=lambda s: s.step_number):
            duration = f" _(~{step.duration_minutes} min)_" if step.duration_minutes else ""
            st.checkbox(f"**{step.step_number}.** {step.instruction}{duration}",
                        key=f"step_{step.step_number}")
        if recipe.tips:
            st.subheader("Chef's tips")
            for tip in recipe.tips:
                st.info(tip, icon="💡")

    with tab_subs:
        if recipe.substitutions:
            st.dataframe(pd.DataFrame([s.model_dump() for s in recipe.substitutions]),
                         hide_index=True, use_container_width=True)
        else:
            st.write("No substitutions were needed.")

    with tab_nut:
        n = recipe.nutrition_per_serving
        if n:
            n1, n2, n3, n4 = st.columns(4)
            n1.metric("Calories", n.calories or "—")
            n2.metric("Protein", f"{n.protein_g} g" if n.protein_g is not None else "—")
            n3.metric("Carbs", f"{n.carbs_g} g" if n.carbs_g is not None else "—")
            n4.metric("Fat", f"{n.fat_g} g" if n.fat_g is not None else "—")
            st.caption("Estimates per serving, generated by the model.")
        else:
            st.write("No nutrition estimate available.")

    with tab_json:
        json_str = recipe.model_dump_json(indent=2)
        st.json(json_str)
        st.download_button("Download JSON", json_str,
                           file_name=f"{recipe.dish_name}.json", mime="application/json")
